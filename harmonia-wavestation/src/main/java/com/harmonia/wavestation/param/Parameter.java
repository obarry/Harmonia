    /** Number of parameters (the {@code PARAM_END} value of the table). */
    public static final int COUNT = 484;

    /** Area of the device a parameter belongs to. */
    public enum Group {
        SELECTION, MIDI, PROGRAM_MAP, MULTISET, SYSEX, GLOBAL, UTILITY, PART, PATCH, WAVE, WAVE_SEQUENCE, MIX,
        COPY, SCALE, EFFECTS, ANALOG_INPUT, DEMO, DIAGNOSTIC, EXECUTE
    }

    /** Context that must be selected on the device before the parameter is sent. */
    public enum Scope {
        /** Global, or applies to the current performance. */
        NONE,
        /** Applies to the part selected with CURRENT_PART (part and patch parameters). */
        PART,
        /** Applies to the wave selected with CURRENT_WAVE in the current part. */
        WAVE,
        /** Applies to the effect selected with CURRENT_FX. */
        FX,
        /** Applies to the mix envelope point selected with MIX_ENV_POINT. */
        MIX_POINT,
        /** Applies to the wave sequence step selected with WAVE_SEQ_STEP. */
        WAVESEQ_STEP
    }

    /** How the parameter is used. */
    public enum Kind {
        /** A number. */
        VALUE,
        /** A name (ASCII text, up to 16 characters). */
        TEXT,
        /** Selects the context of other parameters (current part, wave, effect...). */
        SELECTOR,
        /** Executes a command (EXECUTE_...). */
        ACTION,
        /** Shown by the device, not meant to be changed (names of referenced items, diagnostics). */
        READ_ONLY
    }

    private static final Parameter[] BY_NUMBER = values();

    private final int number;
    private final Group group;
    private final Scope scope;
    private final Kind kind;

    Parameter(int number, Group group, Scope scope, Kind kind) {
        this.number = number;
        this.group = group;
        this.scope = scope;
        this.kind = kind;
    }

    /** Parameter number, as sent in the parameter change message. */
    public int number() {
        return number;
    }

    public Group group() {
        return group;
    }

    public Scope scope() {
        return scope;
    }

    public Kind kind() {
        return kind;
    }

    /** Parameter with the given number. */
    public static Parameter of(int number) {
        if (number < 0 || number >= COUNT) {
            throw new IllegalArgumentException("no parameter " + number);
        }
        return BY_NUMBER[number];
    }

    /** Official name, e.g. "PART_VOLUME". */
    public String officialName() {
        return name();
    }

    /** Readable name, e.g. "Part volume". */
    public String label() {
        String s = name().replace('_', ' ').toLowerCase(Locale.ROOT);
        return Character.toUpperCase(s.charAt(0)) + s.substring(1);
    }

    /** True if the parameter can be changed by a parameter change message. */
    public boolean isEditable() {
        return kind == Kind.VALUE || kind == Kind.TEXT || kind == Kind.SELECTOR;
    }
